use super::*;

#[test]
fn formats_known_timestamps() {
    let cases: &[(u64, &str)] = &[
        (0, "1970-01-01T00:00:00Z"),
        (86399, "1970-01-01T23:59:59Z"),
        (5097600, "1970-03-01T00:00:00Z"),
        (946684799, "1999-12-31T23:59:59Z"),
        (951782400, "2000-02-29T00:00:00Z"),
        (951868800, "2000-03-01T00:00:00Z"),
        (978307200, "2001-01-01T00:00:00Z"),
        (1682812800, "2023-04-30T00:00:00Z"),
        (1682899200, "2023-05-01T00:00:00Z"),
        (1690797600, "2023-07-31T10:00:00Z"),
        (1690884000, "2023-08-01T10:00:00Z"),
        (1696068000, "2023-09-30T10:00:00Z"),
        (1698746400, "2023-10-31T10:00:00Z"),
        (1709209845, "2024-02-29T12:30:45Z"),
        (1735689599, "2024-12-31T23:59:59Z"),
        (1738303628, "2025-01-31T06:07:08Z"),
        (1794390124, "2026-11-11T09:42:04Z"),
        (4107542399, "2100-02-28T23:59:59Z"),
        (4107542400, "2100-03-01T00:00:00Z"),
        (13574566923, "2400-02-29T01:02:03Z"),
    ];
    for (secs, expected) in cases {
        assert_eq!(iso8601(*secs), *expected, "{secs}");
    }
}

#[test]
fn display_form_is_short_and_readable() {
    assert_eq!(display("2026-11-11T09:42:04Z"), "2026-11-11 09:42 UTC");
}

#[test]
fn display_leaves_unrecognised_text_alone() {
    assert_eq!(display(""), "");
    assert_eq!(display("yesterday"), "yesterday");
    assert_eq!(display("2026-11-11 09:42:04Z"), "2026-11-11 09:42:04Z");
    assert_eq!(display("2026-11-11T09:42:04"), "2026-11-11T09:42:04");
    assert_eq!(
        display("2026-11-11T09:42:04+0100"),
        "2026-11-11T09:42:04+0100"
    );
    assert_eq!(display("2026-11-11T09:42:04X"), "2026-11-11T09:42:04X");
    // 20 bytes with 'T' and 'Z' in the right places, but not ASCII: must not be sliced.
    assert_eq!(display("éééééTééééZ"), "éééééTééééZ");
}
